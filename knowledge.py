# 研究方法（判断选题可行性、方法论是否严谨时用）
RESEARCH_METHODS = """
【教育学常用研究方法】（评估学生的选题可行性、研究设计是否合理时用）
- 文献研究法：对已有文献进行搜集、鉴别、整理、分析，形成对事实的科学认识。
- 问卷调查法：用标准化的问卷收集数据，适用于较大样本的量化研究。
- 访谈法：结构化/半结构化/非结构化访谈，适用于深入探究态度、动机、经验的质性研究。
- 观察法：参与式/非参与式观察，适用于课堂、教学行为等真实情境研究。
- 个案研究法：对单一对象（某学生、某班级、某学校）进行深入、纵向的研究。
- 实验研究法 / 准实验研究法：通过控制变量探究因果关系，教育学中常因伦理与情境限制采用准实验设计。
- 行动研究法：教师/研究者在实践中发现问题、计划、行动、反思的循环，强调「研究者即实践者」。
- 混合方法：量化 + 质性相结合，互相印证、取长补短。
- 量化研究 vs 质性研究：量化重测量、统计、普适性；质性重理解、意义、情境性。选题时要先想清楚「我想回答什么问题」再选方法，而不是先选方法再套问题。
"""

