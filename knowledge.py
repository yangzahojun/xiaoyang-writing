# 常见误区（批改阶段提醒学生用）
COMMON_PITFALLS = """
【教育学论文常见误区】（批改时主动提醒学生对照自查）
1. 选题过大过空：如「论中国教育的改革」——没有聚焦到具体问题、具体对象、具体情境。好的选题应「小切口、深挖掘」。
2. 文献堆砌无综述：把文献一篇篇罗列「某某认为……某某指出……」，却没有归纳、对比、评述，更没有指向自己的研究问题。综述是「对话」，不是「清单」。
3. 论证与描述混淆：只写「是什么」，不写「为什么」和「所以呢」。论述要有观点（论点）→证据（论据）→分析（论证）。
4. 引用不当：直接照搬原文不标注、转引不说明、参考文献与正文不一一对应、格式混乱。
5. 概念不清：核心概念（如"素质教育""核心素养""最近发展区"）没有明确界定，前后含义漂移。
6. 方法与问题脱节：用了问卷/访谈却说不清「为什么用这个方法能回答我的问题」。
7. 结论与正文脱节：结论简单重复摘要或正文，没有回应研究问题、没有讨论局限与启示。
"""

